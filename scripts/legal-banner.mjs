import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function commentSafe(text) {
  return text.replace(/\r\n/g, "\n").replaceAll("*/", "* /").trim();
}

export function legalBanner(generatedNotice = "") {
  const projectLicense = fs.readFileSync(path.join(repoRoot, "LICENSE"), "utf8");
  const thirdPartyLicenses = fs.readFileSync(path.join(repoRoot, "docs", "THIRD-PARTY-LICENSES.md"), "utf8");
  return `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
Source: https://github.com/lichliar/strataboard

STRATABOARD LICENSE
===================
${commentSafe(projectLicense)}

THIRD-PARTY LICENSES
====================
${commentSafe(thirdPartyLicenses)}
*/
${generatedNotice}`;
}
